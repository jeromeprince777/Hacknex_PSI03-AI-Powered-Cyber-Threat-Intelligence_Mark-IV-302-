"""
ThreatWeave Entity Graph Builder & Incident Subgraph Extraction.
Models security relationships in NetworkX and exports bounded graph data for Cytoscape.js / React Flow.
Strictly adheres to docs/02_TECHNICAL_PRD.md Section 6.
"""

from __future__ import annotations
from typing import Any, Dict, List, Optional, Set
import networkx as nx

from app.schemas.events import Stage, ThreatWeaveEvent


class EntityGraphBuilder:
    """
    Constructs a multi-relational cybersecurity entity graph and extracts
    focused, readable 1-hop subgraphs for incident investigation.
    """

    def __init__(self) -> None:
        self.graph = nx.MultiDiGraph()

    def add_event(self, event: ThreatWeaveEvent) -> None:
        """
        Adds an event node and creates structural edges to its associated entities.
        """
        ev_id = f"event:{event.event_id}"
        self.graph.add_node(
            ev_id,
            node_id=ev_id,
            label=f"{event.event_type} ({event.event_id})",
            node_type="Event",
            event_id=event.event_id,
            timestamp=event.timestamp,
            source=event.source,
            action=event.action,
        )

        # 1. User Entity
        if event.user_id:
            user_node = f"user:{event.user_id}"
            if not self.graph.has_node(user_node):
                self.graph.add_node(user_node, node_id=user_node, label=event.user_id, node_type="User")
            self.graph.add_edge(ev_id, user_node, relation="GENERATED_BY_USER", label="generated by")

        # 2. Device Entity
        if event.device_id:
            dev_node = f"device:{event.device_id}"
            if not self.graph.has_node(dev_node):
                self.graph.add_node(dev_node, node_id=dev_node, label=event.device_id, node_type="Device")
            self.graph.add_edge(ev_id, dev_node, relation="OCCURRED_ON", label="occurred on")

            if event.user_id:
                user_node = f"user:{event.user_id}"
                self.graph.add_edge(user_node, dev_node, relation="USED_DEVICE", label="used")

        # 3. Source IP Entity
        if event.src_ip:
            ip_node = f"ip:{event.src_ip}"
            if not self.graph.has_node(ip_node):
                self.graph.add_node(ip_node, node_id=ip_node, label=event.src_ip, node_type="IP")
            self.graph.add_edge(ev_id, ip_node, relation="FROM_IP", label="sourced from")

            if event.user_id and event.event_type == "login_success":
                user_node = f"user:{event.user_id}"
                self.graph.add_edge(user_node, ip_node, relation="AUTHENTICATED_FROM", label="auth from")

        # 4. Destination IP Entity
        if event.dst_ip:
            dst_ip_node = f"ip:{event.dst_ip}"
            if not self.graph.has_node(dst_ip_node):
                self.graph.add_node(dst_ip_node, node_id=dst_ip_node, label=event.dst_ip, node_type="IP")
            self.graph.add_edge(ev_id, dst_ip_node, relation="CONNECTED_TO_IP", label="connected to")

        # 5. Resource / File Entity
        if event.resource:
            res_node = f"resource:{event.resource}"
            if not self.graph.has_node(res_node):
                self.graph.add_node(res_node, node_id=res_node, label=event.resource, node_type="Resource")
            self.graph.add_edge(ev_id, res_node, relation="TARGETED_RESOURCE", label="targeted")

            if event.user_id:
                user_node = f"user:{event.user_id}"
                self.graph.add_edge(user_node, res_node, relation="ACCESSED_RESOURCE", label="accessed")

        # 6. Removable Device / USB Entity
        usb_id = event.attributes.get("removable_media_id")
        if usb_id:
            usb_node = f"removable:{usb_id}"
            if not self.graph.has_node(usb_node):
                self.graph.add_node(
                    usb_node,
                    node_id=usb_node,
                    label=f"USB: {usb_id}",
                    node_type="RemovableDevice",
                    vendor=event.attributes.get("vendor"),
                )
            self.graph.add_edge(ev_id, usb_node, relation="ATTACHED_TO_MEDIA", label="media attached")

            if event.device_id:
                dev_node = f"device:{event.device_id}"
                self.graph.add_edge(dev_node, usb_node, relation="MOUNTED_USB", label="mounted")

        # 7. Application Entity
        if event.application:
            app_node = f"application:{event.application}"
            if not self.graph.has_node(app_node):
                self.graph.add_node(app_node, node_id=app_node, label=event.application, node_type="Application")
            self.graph.add_edge(ev_id, app_node, relation="EXECUTED_BY", label="executed by")

    def add_events_batch(self, events: List[ThreatWeaveEvent]) -> None:
        """Batch loads events into graph."""
        for ev in events:
            self.add_event(ev)

    def extract_incident_subgraph(
        self,
        incident_id: str,
        stages: List[Stage],
        evidence_events: List[ThreatWeaveEvent],
    ) -> Dict[str, Any]:
        """
        Constructs a focused 1-hop subgraph containing only the incident's evidence
        events, stages, and their directly connected entities.
        Prevents visual clutter in the investigation console.
        """
        # Node IDs to include in bounded view
        target_nodes: Set[str] = set()

        # Add incident node
        inc_node_id = f"incident:{incident_id}"
        target_nodes.add(inc_node_id)

        # Add stages and their relationships
        for stage in stages:
            stg_node_id = f"stage:{stage.stage_id}"
            target_nodes.add(stg_node_id)
            for eid in stage.evidence_event_ids:
                target_nodes.add(f"event:{eid}")

        # Expand 1-hop to connected direct entities (User, Device, IP, Resource, Removable)
        for ev in evidence_events:
            ev_node_id = f"event:{ev.event_id}"
            target_nodes.add(ev_node_id)
            if self.graph.has_node(ev_node_id):
                for neighbor in self.graph.neighbors(ev_node_id):
                    target_nodes.add(neighbor)
                # Also include predecessors (e.g. user -> device)
                for pred in self.graph.predecessors(ev_node_id):
                    target_nodes.add(pred)

        # Build Cytoscape/React Flow compatible node and edge list
        nodes_list: List[Dict[str, Any]] = []
        edges_list: List[Dict[str, Any]] = []

        # 1. Incident node
        nodes_list.append({
            "id": inc_node_id,
            "label": f"Incident {incident_id}",
            "type": "Incident",
            "data": {"incident_id": incident_id},
        })

        # 2. Stage nodes
        for stage in stages:
            stg_node_id = f"stage:{stage.stage_id}"
            nodes_list.append({
                "id": stg_node_id,
                "label": f"Stage {stage.sequence_index}: {stage.name}",
                "type": "Stage",
                "data": {
                    "stage_id": stage.stage_id,
                    "sequence_index": stage.sequence_index,
                    "evidence_count": len(stage.evidence_event_ids),
                },
            })
            # Edge: Stage -> Incident
            edges_list.append({
                "id": f"edge:{stg_node_id}->{inc_node_id}",
                "source": stg_node_id,
                "target": inc_node_id,
                "label": "BELONGS_TO",
            })

            # Edge: Event -> Stage
            for eid in stage.evidence_event_ids:
                ev_nid = f"event:{eid}"
                edges_list.append({
                    "id": f"edge:{ev_nid}->{stg_node_id}",
                    "source": ev_nid,
                    "target": stg_node_id,
                    "label": "SUPPORTS",
                })

        # 3. Entity and Event nodes from NetworkX graph
        for nid in target_nodes:
            if nid == inc_node_id or nid.startswith("stage:"):
                continue
            if self.graph.has_node(nid):
                attrs = self.graph.nodes[nid]
                nodes_list.append({
                    "id": nid,
                    "label": attrs.get("label", nid),
                    "type": attrs.get("node_type", "Entity"),
                    "data": attrs,
                })

        # 4. Underlying entity-to-entity and event-to-entity edges
        edge_id_counter = 0
        seen_edges: Set[str] = set()
        for u in target_nodes:
            if not self.graph.has_node(u):
                continue
            for v in self.graph.neighbors(u):
                if v in target_nodes and not v.startswith("incident:") and not v.startswith("stage:"):
                    edge_data_dict = self.graph.get_edge_data(u, v)
                    if edge_data_dict:
                        for k, edata in edge_data_dict.items():
                            edge_key = f"{u}->{v}:{edata.get('relation', '')}"
                            if edge_key not in seen_edges:
                                seen_edges.add(edge_key)
                                edge_id_counter += 1
                                edges_list.append({
                                    "id": f"edge:{edge_id_counter}",
                                    "source": u,
                                    "target": v,
                                    "label": edata.get("label", edata.get("relation", "connected")),
                                    "relation": edata.get("relation", ""),
                                })

        return {
            "incident_id": incident_id,
            "nodes": nodes_list,
            "edges": edges_list,
            "total_nodes": len(nodes_list),
            "total_edges": len(edges_list),
        }
